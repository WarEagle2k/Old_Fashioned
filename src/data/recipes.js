export const getRecipesBySpirit = (spiritId) => {
  if (!spiritId || spiritId === 'all') return recipes;
  return recipes.filter((r) => r.spirit === spiritId);
};

export const getRecipeById = (id) => {
  return recipes.find((r) => r.id === id);
};

export const getTopRecipes = (count = 3) => {
  return [...recipes].sort((a, b) => b.rating - a.rating).slice(0, count);
};
